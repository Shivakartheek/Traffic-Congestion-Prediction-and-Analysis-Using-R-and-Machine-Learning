# =============================================================================
# run_pipeline.R  -  Runs the WHOLE project from the console (no Shiny needed)
#
# Usage (in RStudio, with the project folder as working directory):
#     source("run_pipeline.R")
#
# What it does
#   1. Creates the synthetic dataset (if it does not exist)
#   2. Shows "before" and "after" dataset information
#   3. Calculates statistics and saves the 10 EDA graphs (outputs/plots/)
#   4. Trains Logistic Regression, Decision Tree and Random Forest
#   5. Evaluates them on the test data and saves models/trained_model.rds
#   6. Writes outputs/results_summary.md  <- REAL numbers to paste in your report
# =============================================================================

source("R/data_preprocessing.R")
source("R/analysis.R")
source("R/visualization.R")
source("R/model_training.R")

dir.create("data",          showWarnings = FALSE)
dir.create("models",        showWarnings = FALSE)
dir.create("outputs/plots", showWarnings = FALSE, recursive = TRUE)

# ---- 1. Dataset ---------------------------------------------------------------
if (!file.exists("data/traffic_data.csv")) {
  cat("Creating synthetic dataset (seed = 123) ...\n")
  readr::write_csv(generate_traffic_data(n = 1500, seed = 123), "data/traffic_data.csv")
}
file.copy("data/traffic_data.csv", "traffic_data.csv", overwrite = TRUE)  # copy in project root
ds <- load_or_create_dataset()
cat("Dataset loaded from:", ds$source, "\n")

# ---- 2. Preprocessing (prints before / after information) -------------------------
prep <- preprocess_traffic_data(ds$data, verbose = TRUE)
clean <- prep$data
readr::write_csv(clean, "data/traffic_data_clean.csv")

cat("\n===== ENCODED CATEGORICAL VARIABLES (first 5 rows) =====\n")
print(as.data.frame(head(prep$encoded[, c("Day_of_Week", "Day_Code", "Accident", "Accident_Code",
                                            "Road_Type", "RoadType_Code",
                                            "Congestion_Level", "Congestion_Code")], 5)))

# ---- 3. Statistics and graphs --------------------------------------------------------
stats <- compute_statistics(clean)
cat("\n===== STATISTICS =====\n")
print(as.data.frame(stats$table))
cat("\nCorrelation (vehicle count, speed)    :", round(stats$cor_vc_speed, 4), "\n")
cat("Correlation (rainfall, vehicle count) :", round(stats$cor_rain_vc, 4), "\n")
cat("\n===== WHAT THE NUMBERS MEAN =====\n")
cat(paste0("- ", interpret_statistics(stats)), sep = "\n")

cat("\n===== AVERAGE CONDITIONS PER CONGESTION LEVEL =====\n")
print(as.data.frame(congestion_profile(clean)))

plots <- all_eda_plots(clean)
for (nm in names(plots)) {
  ggplot2::ggsave(file.path("outputs/plots", paste0(nm, ".png")), plots[[nm]],
                  width = 8, height = 5, dpi = 120, bg = "white")
}
cat("\nSaved", length(plots), "EDA graphs in outputs/plots/\n")

# ---- 4 + 5. Models ----------------------------------------------------------------------
cat("\nTraining the three models (this takes a few seconds) ...\n")
bundle <- train_all_models(clean, seed = 123)
save_bundle(bundle, "models/trained_model.rds")

cat("\n===== MODEL COMPARISON (test data, macro-averaged) =====\n")
print(bundle$metrics, row.names = FALSE)
cat("\nBest model (highest F1-score):", bundle$best_model, "\n")

for (nm in names(bundle$confusion)) {
  cat("\n----- Confusion matrix:", nm, "-----\n")
  print(bundle$confusion[[nm]]$table)
  ggplot2::ggsave(file.path("outputs/plots",
                            paste0("cm_", gsub(" ", "_", tolower(nm)), ".png")),
                  plot_confusion_matrix(bundle$confusion[[nm]], nm),
                  width = 5, height = 4.5, dpi = 120, bg = "white")
}
ggplot2::ggsave("outputs/plots/model_comparison.png", plot_model_comparison(bundle$metrics),
                width = 9, height = 5, dpi = 120, bg = "white")
ggplot2::ggsave("outputs/plots/feature_importance.png",
                plot_feature_importance(head(bundle$importance, 10)),
                width = 8, height = 5, dpi = 120, bg = "white")

# Picture of the decision tree
png("outputs/plots/decision_tree.png", width = 1100, height = 750, res = 110)
plot(bundle$models[["Decision Tree"]]$finalModel, uniform = TRUE, margin = 0.08)
text(bundle$models[["Decision Tree"]]$finalModel, use.n = TRUE, cex = 0.7)
dev.off()

write.csv(bundle$metrics, "outputs/model_comparison.csv", row.names = FALSE)

# ---- 6. Results summary (Markdown) for the project report ---------------------------------
md_table <- function(d) {
  d <- as.data.frame(d)
  header <- paste0("| ", paste(names(d), collapse = " | "), " |")
  sep    <- paste0("|", paste(rep("---", ncol(d)), collapse = "|"), "|")
  rows   <- apply(d, 1, function(r) paste0("| ", paste(trimws(r), collapse = " | "), " |"))
  c(header, sep, rows)
}

summary_lines <- c(
  "# Results Summary (generated by run_pipeline.R)",
  "",
  paste0("Generated on: ", format(Sys.time(), "%Y-%m-%d %H:%M")),
  paste0("Records after cleaning: ", nrow(clean),
         " | Training rows: ", bundle$train_rows, " | Test rows: ", bundle$test_rows,
         " | Random seed: ", bundle$seed),
  "",
  "## Preprocessing: before vs after",
  md_table(prep$comparison),
  "",
  "## Statistics",
  md_table(stats$table),
  "",
  paste0("- Correlation between vehicle count and speed: ", round(stats$cor_vc_speed, 4),
         " (", describe_correlation(stats$cor_vc_speed), ")"),
  paste0("- Correlation between rainfall and vehicle count: ", round(stats$cor_rain_vc, 4),
         " (", describe_correlation(stats$cor_rain_vc), ")"),
  "",
  "## Model comparison (20% test data, macro-averaged)",
  md_table(bundle$metrics),
  "",
  paste0("**Best model (highest F1-score): ", bundle$best_model, "**"),
  "",
  "## Per-class metrics",
  md_table(bundle$per_class),
  "",
  "## Confusion matrices (rows = predicted, columns = actual)",
  unlist(lapply(names(bundle$confusion), function(nm) {
    tb <- as.data.frame.matrix(bundle$confusion[[nm]]$table)
    tb <- cbind(Predicted = rownames(tb), tb)
    c(paste0("### ", nm), md_table(tb), "")
  }))
)
writeLines(summary_lines, "outputs/results_summary.md")

cat("\nDONE. Files created:\n",
    " - data/traffic_data.csv, traffic_data.csv, data/traffic_data_clean.csv\n",
    " - models/trained_model.rds\n",
    " - outputs/plots/*.png\n",
    " - outputs/model_comparison.csv\n",
    " - outputs/results_summary.md  (paste these real numbers into your report)\n")
